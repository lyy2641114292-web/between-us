/**
 * 按轮次取兜底内容；超出范围时重复最后一轮，并标记 done。
 * @param {number} index 已完成的轮数（0 起）
 */
export function fallbackRoundAt(index) {
  const i = Math.min(Math.max(index, 0), S3_FALLBACK_ROUNDS.length - 1)
  return S3_FALLBACK_ROUNDS[i]
}
