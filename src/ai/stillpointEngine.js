// 各阶段在抽屉顶部的「当前观测焦点」文案（原型 syncStillpointForCurrentStage）
export function getStageFocusLabel(stageIndex, activeContextKey) {
  const ctx = STILLPOINT_CONTEXT_ENGINE[activeContextKey] || STILLPOINT_CONTEXT_ENGINE.delay26
  const map = {
    '-1': '欢迎来到 Between Us · 关系视角探索',
    0: '01 记录冲突 · 片段梳理陪伴',
    1: '02 理解自己 · 剥离事实与猜测',
    2: '03 探索对方 · 重力实验陪伴',
    3: ctx.focusTitle,
    4: '05 决定下一步 · 尊重你的真实意愿',
  }
  return map[String(stageIndex)] || map['3']
}

// 关键词匹配（原型 processStillpointInteraction）
export function matchBranch(ctxData, userText) {
  if (!ctxData || !ctxData.followUpTree) return null
  return ctxData.followUpTree.find((b) => b.match.some((k) => userText.includes(k))) || null
}

// 未命中时的兜底回复（原型 fallback 分支，文案与原型一致）
export function buildFallbackReply(userText) {
  const short = `${userText.slice(0, 18)}${userText.length > 18 ? '…' : ''}`
  return [
    `听起来你对「${short}」有着很真实的体感。在一段亲密友情出现摩擦时，能这样停下来梳理自己的想法，本身就已经在降低情绪内耗了。`,
    '结合刚才两边星轨对照出的细节，你现在更想继续往下探索哪一个方向？',
  ]
}
